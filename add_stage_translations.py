from women_skills.models import LearningStage

def update_s(skill_name, stage_num, title_hi, desc_hi, title_mr, desc_mr):
    s = LearningStage.objects.get(skill__name=skill_name, stage_number=stage_num)
    s.title_hi = title_hi
    s.description_hi = desc_hi
    s.title_mr = title_mr
    s.description_mr = desc_mr
    s.save()

