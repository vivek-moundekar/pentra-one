def update_translation(name, name_hi, desc_hi, guide_hi, materials_hi, name_mr, desc_mr, guide_mr, materials_mr):
    skill = Skill.objects.get(name=name)
    skill.name_hi = name_hi
    skill.description_hi = desc_hi
    skill.guide_hi = guide_hi
    skill.materials_hi = materials_hi
    skill.name_mr = name_mr
    skill.description_mr = desc_mr
    skill.guide_mr = guide_mr
    skill.materials_mr = materials_mr
    skill.save()

